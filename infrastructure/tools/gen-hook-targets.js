#!/usr/bin/env node
// Game-update watch input. Finds every Harmony hook target the shipped Lua uses and writes
// tests/smoke/Lua/targets.lua. The in-game smoke run resolves each one against the current
// Assembly-CSharp through hooks.check_target and fails on a missing or changed method.
// Run: node infrastructure/tools/gen-hook-targets.js [--check]
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "../..");
const walk = (dir) =>
  fs.existsSync(dir)
    ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
        const p = path.join(dir, e.name);
        return e.isDirectory() ? walk(p) : [p];
      })
    : [];

const sources = [...walk(path.join(root, "src/examples")), ...walk(path.join(root, "mod/Lua")), ...walk(path.join(root, "tests/smoke/Lua"))].filter(
  (f) => f.endsWith(".lua") && !f.endsWith("targets.lua")
);

const callRe = /hooks\s*\.\s*(prefix|postfix|finalizer|replace_call|transpile)\s*\(\s*"([^"]+)"\s*,\s*"([^"]+)"/g;
const targets = new Map();
for (const file of sources) {
  const text = fs.readFileSync(file, "utf8");
  const matches = [...text.matchAll(callRe)];
  matches.forEach((m, i) => {
    const end = i + 1 < matches.length ? matches[i + 1].index : text.length;
    const body = text.slice(m.index, end);
    const sigMatch = /\bsig\s*=\s*\{([^}]*)\}/.exec(body);
    const sig = sigMatch ? [...sigMatch[1].matchAll(/"([^"]+)"/g)].map((s) => s[1]) : [];
    const key = `${m[2]}::${m[3]}(${sig.join(",")})`;
    if (!targets.has(key)) targets.set(key, { type: m[2], method: m[3], sig: sig.join(","), from: path.relative(root, file).split(path.sep).join("/") });
  });
}

const rows = [...targets.values()].sort((a, b) => (a.type + a.method).localeCompare(b.type + b.method));
const lua =
  "-- Generated by infrastructure/tools/gen-hook-targets.js. Do not edit by hand.\n" +
  "return {\n" +
  rows.map((r) => `  { type = ${JSON.stringify(r.type)}, method = ${JSON.stringify(r.method)}, sig = ${JSON.stringify(r.sig)}, from = ${JSON.stringify(r.from)} },`).join("\n") +
  "\n}\n";

const out = path.join(root, "tests/smoke/Lua/targets.lua");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r/g, "") : "";
  if (current !== lua) {
    console.log("hook targets: tests/smoke/Lua/targets.lua is out of date. Run node infrastructure/tools/gen-hook-targets.js");
    process.exit(1);
  }
  console.log(`hook targets: ${rows.length} up to date`);
} else {
  fs.writeFileSync(out, lua);
  console.log(`hook targets: wrote ${rows.length} targets`);
}
