#!/usr/bin/env node
// Generates infrastructure/docs/api/types.md: every table shape the API returns or accepts (RimPawnInfo, RimQuestInfo, ...),
// with its fields and the functions that use it. Sources: the generated Lua stubs and src/api/kits.json.
// Run: node infrastructure/tools/gen-api-types.js [--check]
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "../..");
const out = path.join(root, "infrastructure/docs/api/types.md");
const kits = JSON.parse(fs.readFileSync(path.join(root, "src/api/kits.json"), "utf8")).kits;

const classes = new Map();
const aliases = new Map();
for (const rel of ["src/editor/stubs/rimkit_kits.lua", "src/editor/stubs/rimkit.lua"]) {
  const lines = fs.readFileSync(path.join(root, rel), "utf8").split(/\r?\n/);
  let cur = null;
  let doc = [];
  for (const line of lines) {
    let m;
    if ((m = /^---@class (\w+)(?: : (\w+))?\s*$/.exec(line))) {
      cur = { name: m[1], parent: m[2] || "", fields: [], doc: doc.join(" ") };
      classes.set(cur.name, cur);
      doc = [];
    } else if ((m = /^---@field (\w+)(\?)? (\S+)(?: (.*))?$/.exec(line))) {
      if (cur) cur.fields.push({ name: m[1], optional: !!m[2], type: m[3], doc: (m[4] || "").trim() });
    } else if ((m = /^---@alias (\w+) (.+)$/.exec(line))) {
      aliases.set(m[1], m[2].trim());
      cur = null;
      doc = [];
    } else if (/^---[^@]/.test(line)) {
      doc.push(line.replace(/^---\s?/, "").trim());
    } else if (!/^---@/.test(line)) {
      if (!/^---/.test(line)) cur = null;
      doc = /^---[^@]/.test(line) ? doc : [];
    }
  }
}

// Which functions use each class.
const returnedBy = new Map();
const takenBy = new Map();
const baseName = (t) => (t || "").replace(/\?$/, "").replace(/\[\]$/, "").trim();
const note = (map, type, label) => {
  if (!classes.has(type)) return;
  if (!map.has(type)) map.set(type, []);
  map.get(type).push(label);
};
for (const k of kits) {
  for (const f of k.fns) {
    const label = `game.${k.domain}.${f.name}`;
    note(returnedBy, baseName(f.returns), label);
    for (const p of f.params) for (const part of baseName(p.type).split("|")) note(takenBy, baseName(part), label);
  }
}
for (const c of classes.values()) {
  for (const f of c.fields) {
    for (const part of baseName(f.type).split("|")) {
      const t = baseName(part);
      if (classes.has(t) && t !== c.name) note(takenBy, t, `${c.name}.${f.name}`);
    }
  }
}

const link = (type) => {
  const t = baseName(type);
  return classes.has(t) ? `[${type}](#${t.toLowerCase()})` : `\`${type}\``;
};
const cell = (s) => (s || "").replace(/\|/g, "\\|");
const list = (items) => [...new Set(items)].slice(0, 12).map((x) => "`" + x + "`").join(", ") + (new Set(items).size > 12 ? ", ..." : "");

const names = [...classes.keys()].sort((a, b) => a.localeCompare(b));
const text = [];
text.push("<!-- Generated by infrastructure/tools/gen-api-types.js from the Lua stubs and src/api/kits.json. Do not edit by hand. -->");
text.push("# Types");
text.push("");
text.push(`Every table shape the API returns or accepts: ${names.length} types. A field ending in \`?\` may be missing. Wrapped game objects (\`RimPawn\`, \`RimThing\`, \`RimMap\`, \`RimFaction\`, \`RimObject\`) are userdata with properties and methods, described in [naming](naming.md) and the [reference](reference.md). Every function that takes a pawn, thing, map or faction accepts the wrapped object or its integer handle.`);
text.push("");
if (aliases.size) {
  text.push("## Aliases");
  text.push("");
  text.push("| Alias | Means |");
  text.push("|-------|-------|");
  for (const [a, v] of [...aliases].sort((x, y) => x[0].localeCompare(y[0]))) text.push(`| \`${a}\` | \`${cell(v)}\` |`);
  text.push("");
}
text.push("## Index");
text.push("");
const byLetter = new Map();
for (const n of names) {
  const l = n.replace(/^Rim/, "")[0].toUpperCase();
  if (!byLetter.has(l)) byLetter.set(l, []);
  byLetter.get(l).push(`[${n}](#${n.toLowerCase()})`);
}
for (const [l, items] of byLetter) text.push(`**${l}** ${items.join(", ")}
`);
text.push("");
text.push("## Definitions");
for (const n of names) {
  const c = classes.get(n);
  text.push("");
  text.push(`### ${n}`);
  text.push("");
  if (c.doc) text.push(c.doc + "\n");
  if (c.parent) text.push(`Extends ${link(c.parent)}.\n`);
  if (c.fields.length) {
    text.push("| Field | Type | Meaning |");
    text.push("|-------|------|---------|");
    for (const f of c.fields) text.push(`| \`${f.name}${f.optional ? "?" : ""}\` | ${link(f.type)} | ${cell(f.doc)} |`);
  } else {
    text.push("No fields.");
  }
  const r = returnedBy.get(n);
  const t = takenBy.get(n);
  if (r) text.push(`\nReturned by ${list(r)}.`);
  if (t) text.push(`\nUsed by ${list(t)}.`);
}
text.push("");
const body = text.join("\n");

// Every field needs a meaning, so a new type cannot ship with an empty column.
const bare = [];
for (const c of classes.values()) for (const f of c.fields) if (!f.doc) bare.push(c.name + "." + f.name);

if (process.argv.includes("--check")) {
  if (bare.length) {
    console.log("api types: " + bare.length + " field(s) have no description, for example " + bare.slice(0, 5).join(", ") + ". Add one in src/api/kits/*.kit or src/editor/stubs/rimkit.lua");
    process.exit(1);
  }
  const same = fs.existsSync(out) && fs.readFileSync(out, "utf8").replace(/\r/g, "") === body;
  console.log(`api types: ${names.length} types, ${same ? "up to date" : "OUT OF DATE, run node infrastructure/tools/gen-api-types.js"}`);
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(out, body);
console.log(`api types: wrote ${names.length} types`);
