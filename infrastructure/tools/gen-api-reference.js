#!/usr/bin/env node
// Generates infrastructure/docs/api/reference.md from aliases + Lua stubs.
// Sources:
//   src/api/aliases.json
//   src/editor/stubs/rimkit_unc.lua
//   src/editor/stubs/rimkit.lua
// Run: node infrastructure/tools/gen-api-reference.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "../..");
// Coverage: a function counts as tested when the in-game smoke suite (tests/smoke) or the native tests call it.
const testSources = ["tests/smoke/Lua/main.lua", "tests/native/aliastest.lua", "tests/native/budget_noisy.lua", "tests/native/kits_args.lua"]
  .map((p) => path.join(root, p))
  .filter((p) => fs.existsSync(p))
  .map((p) => fs.readFileSync(p, "utf8"))
  .join("\n");
const isTested = (fnPath) => {
  const escaped = fnPath.split(".").join("\\s*\\.\\s*");
  return new RegExp("\\b" + escaped + "\\s*\\(").test(testSources);
};
let testedCount = 0;
let totalCount = 0;
const aliases = JSON.parse(fs.readFileSync(path.join(root, "src", "api", "aliases.json"), "utf8"));
const stubFiles = ["src/editor/stubs/rimkit.lua", "src/editor/stubs/rimkit_unc.lua", "src/editor/stubs/rimkit_kits.lua"];

const oldNames = new Map();
for (const g of aliases.groups) {
  for (const entry of g.names) {
    const gt = entry.indexOf(">");
    const oldName = gt >= 0 ? entry.slice(0, gt) : entry;
    const newName = gt >= 0 ? entry.slice(gt + 1) : entry;
    const oldPath = `${g.from}.${oldName}`;
    const newPath = newName.includes(".") ? `game.${newName}` : `${g.to}.${newName}`;
    if (g.deprecate === false || oldPath === newPath) continue;
    if (!oldNames.has(newPath)) oldNames.set(newPath, []);
    oldNames.get(newPath).push(oldPath);
  }
}

const functions = new Map();
for (const rel of stubFiles) {
  const lines = fs.readFileSync(path.join(root, rel), "utf8").split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const m = /^function (game\.[\w.]+)\((.*)\) end\s*$/.exec(lines[i]);
    if (!m) continue;
    let start = i;
    while (start > 0 && /^---/.test(lines[start - 1])) start--;
    const block = lines.slice(start, i);
    const info = { path: m[1], params: m[2], description: [], paramDocs: [], returns: [], deprecated: false };
    for (const b of block) {
      let t;
      if ((t = /^---@param (\S+) (\S+)(?: (.*))?$/.exec(b))) info.paramDocs.push({ name: t[1], type: t[2], note: t[3] || "" });
      else if ((t = /^---@return (\S+)(?: (.*))?$/.exec(b))) info.returns.push({ type: t[1], note: t[2] || "" });
      else if (/^---@deprecated/.test(b)) info.deprecated = true;
      else if (/^---[^@]/.test(b)) info.description.push(b.replace(/^---\s?/, ""));
    }
    if (!functions.has(info.path) || rel.endsWith("rimkit.lua")) functions.set(info.path, info);
  }
}

const domains = new Map();
for (const info of functions.values()) {
  if (info.deprecated) continue;
  const parts = info.path.split(".");
  if (parts.length < 3) continue;
  const domain = parts[1];
  if (!domains.has(domain)) domains.set(domain, []);
  domains.get(domain).push(info);
}

const titles = {
  pawns: "Pawns", things: "Things", maps: "Maps", factions: "Factions", time: "Time", world: "World", weather: "Weather",
  incidents: "Incidents", jobs: "Jobs", paths: "Paths and movement", defs: "Defs", ui: "UI", config: "Config",
  data: "Saved data", input: "Input", events: "Events", log: "Logging", timer: "Timers", util: "Utilities",
  buildings: "Buildings", work: "Work", audio: "Audio", control: "Control", anomaly: "Anomaly (DLC)", selection: "Selection",
  hooks: "Hooks (Harmony)", reflect: "Typed reflection (Advanced)", query: "Queries", camera: "Camera", inventory: "Inventory", version: "Version",
};
const intro = {
  pawns: "Kit page: [pawns](pawns.md).",
  maps: "Kit page: [maps](maps.md).",
  jobs: "Kit page: [jobs](jobs.md).",
  things: "Kit page: [things](things.md).",
  factions: "Kit page: [factions](factions.md).",
  time: "Kit page: [time](time.md).",
  query: "Kit page: [queries](query.md).",
  selection: "Kit page: [selection and camera](selection.md).",
  camera: "Kit page: [selection and camera](selection.md).",
  anomaly: "Kit page: [anomaly](anomaly.md).",
  hooks: "Guide: [hooks](hooks.md). Advanced tier.",
  reflect: "Guide: [reflect](reflect.md). Advanced tier, needs the `developer_reflect` setting.",
  events: "Named events: [events](events.md).",
};

const out = [];
out.push("<!-- Generated by infrastructure/tools/gen-api-reference.js from src/api/aliases.json and the Lua stubs. Do not edit by hand. -->");
out.push("# API reference");
out.push("");
out.push("Every canonical function under `game`. Names follow the [naming convention](naming.md). A function marked with an old name is the new home of that name, which still works until " + aliases.removed_in + " and prints one deprecation line. See [migration](migration.md).");
out.push("");
out.push("Arguments named `pawn`, `thing`, `map` accept the wrapped object (`RimPawn`, `RimThing`, `RimMap`) or its integer handle. Functions that act on a pawn take it as the first argument.");
out.push("");
const names = [...domains.keys()].sort((a, b) => (titles[a] || a).localeCompare(titles[b] || b));
out.push("Domains: " + names.map((n) => `[${titles[n] || n}](#${(titles[n] || n).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")})`).join(", ") + ".");
out.push("");
for (const name of names) {
  out.push(`## ${titles[name] || name}`);
  out.push("");
  if (intro[name]) {
    out.push(intro[name]);
    out.push("");
  }
  out.push("| Function | Parameters | Returns | Notes |");
  out.push("|----------|------------|---------|-------|");
  const list = domains.get(name).sort((a, b) => a.path.localeCompare(b.path));
  for (const f of list) {
    const params = f.params || "";
    const returns = f.returns.map((r) => "`" + r.type + "`" + (r.note ? " " + r.note : "")).join(", ");
    const notes = [];
    if (f.description.length) notes.push(f.description.join(" "));
    const nameDocs = f.paramDocs.filter((p) => p.note).map((p) => `\`${p.name}\`: ${p.note}`);
    if (nameDocs.length) notes.push(nameDocs.join("; "));
    totalCount++;
    if (isTested(f.path)) {
      testedCount++;
      notes.push("Tested.");
    }
    const olds = oldNames.get(f.path);
    if (olds && olds.length) notes.push("Old: " + olds.map((o) => "`" + o + "`").join(", "));
    const esc = (s) => s.replace(/\|/g, "\\|");
    out.push(`| \`${f.path}\` |${params ? "`" + esc(params) + "`" : ""} | ${esc(returns)} | ${esc(notes.join(" "))} |`);
  }
  out.push("");
}
out.splice(
  out.findIndex((l) => l.startsWith("Domains:")),
  0,
  `Coverage: ${testedCount} of ${totalCount} functions are called by the smoke or native tests and are marked **Tested**.`,
  "",
  "The rest of the surface: [types](types.md) (every table shape a function returns or takes), [events](events.md), [tweaks](tweaks.md), [Lua classes](classes.md), [host operations](ops.md) (what each function sends to the game) and the [CLI reference](../guide/cli.md).",
  ""
);
out.push("## Wrapped objects");
out.push("");
out.push("Methods and properties on `RimPawn`, `RimThing`, `RimMap`, `RimFaction`, `RimEntity` and `RimObject` are documented in the Lua stubs (`src/editor/stubs/rimkit.lua`) and shown by the editor extension. The pawn members are listed in [pawns](pawns.md).");
out.push("");

fs.writeFileSync(path.join(root, "infrastructure", "docs", "api", "reference.md"), out.join("\n"));
console.log(`gen-api-reference: ${[...domains.values()].reduce((n, l) => n + l.length, 0)} functions in ${domains.size} domains`);
