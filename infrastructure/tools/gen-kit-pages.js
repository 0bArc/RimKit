#!/usr/bin/env node
// Generates the kit pages in infrastructure/docs/api from the prose in infrastructure/api-src/pages.md and the kit table.
// Each section of pages.md starts with "=== <page> | <title> ===" and holds the introduction and examples. The placeholder
// {{functions}} is replaced by a table of every function whose kit names that page, with parameters, result and description.
// Run: node infrastructure/tools/gen-kit-pages.js [--check]
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "../..");
const kits = JSON.parse(fs.readFileSync(path.join(root, "src/api/kits.json"), "utf8")).kits;
const source = fs.readFileSync(path.join(root, "infrastructure/api-src/pages.md"), "utf8").replace(/\r/g, "");
const outDir = path.join(root, "infrastructure/docs/api");

const sections = [];
for (const m of source.matchAll(/^=== (\w+) \| (.+?) ===\n([\s\S]*?)(?=^=== |\s*$(?![\s\S]))/gm)) sections.push({ page: m[1], title: m[2], body: m[3].replace(/\s+$/, "") });

const esc = (s) => String(s).replace(/\|/g, "\\|");
function table(page) {
  const rows = [];
  for (const k of kits) {
    if (k.page !== page) continue;
    for (const f of k.fns) {
      const params = (f.params || []).map((p) => (p.optional ? p.name + "?" : p.name)).join(", ");
      rows.push(`| \`game.${k.domain}.${f.name}\` | ${params ? "`" + esc(params) + "`" : ""} | ${f.returns ? "`" + esc(f.returns) + "`" : ""} | ${esc(f.doc)} |`);
    }
  }

  return ["| Function | Parameters | Returns | Description |", "|----------|------------|---------|-------------|", ...rows].join("\n");
}

let stale = 0;
for (const s of sections) {
  const text = `<!-- Generated by infrastructure/tools/gen-kit-pages.js from infrastructure/api-src/pages.md and src/api/kits.json. Do not edit by hand. -->\n# ${s.title}\n\n${s.body.replace("{{functions}}", "## Functions\n\n" + table(s.page))}\n`;
  const file = path.join(outDir, s.page + ".md");
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r/g, "") : "";
    if (current !== text) {
      console.log(`kit pages: ${path.relative(root, file)} is out of date. Run node infrastructure/tools/gen-kit-pages.js`);
      stale++;
    }
  } else {
    fs.writeFileSync(file, text);
  }
}

if (!process.argv.includes("--check")) console.log(`kit pages: wrote ${sections.length} pages`);
else console.log(`kit pages: ${sections.length} pages, ${stale} out of date`);
process.exit(stale ? 1 : 0);
